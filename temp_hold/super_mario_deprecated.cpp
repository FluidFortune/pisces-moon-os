// ─────────────────────────────────────────────
//  RUNTIME LEVEL STATE
//
//  At level load time we copy the const data into a mutable
//  grid (so bricks can pop and disappear), extract entity
//  spawn cells into the entity list, and compute the width.
//
//  MAX_LEVEL_W bounds the grid array. The largest level above
//  is 80 chars wide; bump this if you add wider levels.
// ─────────────────────────────────────────────
static constexpr int MAX_LEVEL_W = 192;
static char  grid[LEVEL_ROWS][MAX_LEVEL_W + 1];
static int   level_w = 0;

static char tile_at(int tx, int ty) {
    if (tx < 0 || tx >= level_w || ty < 0 || ty >= LEVEL_ROWS) {
        // Outside the level grid: bottom is "kill plane" (player
        // falls into the void), top/sides are sky/solid wall.
        if (ty >= LEVEL_ROWS) return '~';   // treat as lava for death plane
        return '.';
    }
    return grid[ty][tx];
}

static void set_tile(int tx, int ty, char c) {
    if (tx < 0 || tx >= level_w || ty < 0 || ty >= LEVEL_ROWS) return;
    grid[ty][tx] = c;
}

// ─────────────────────────────────────────────
//  ENTITIES (player, enemies, pickups, effects)
// ─────────────────────────────────────────────
enum EntityKind {
    EK_DEAD = 0,
    EK_COIN,
    EK_MUSHROOM,
    EK_STAR,
    EK_GOOMBA,
    EK_KOOPA,         // walking turtle
    EK_KOOPA_SHELL,   // stunned shell (kickable)
    EK_KOOPA_SLIDE,   // kicked shell sliding
    EK_BUMP_PARTICLE, // visual brick chunk
    EK_COIN_POP,      // brief "+200" floater
};

struct Entity {
    EntityKind kind;
    int32_t    x_q8;    // pixel x in 1/256ths (fixed-point)
    int32_t    y_q8;    // pixel y in 1/256ths
    int32_t    vx_q8;   // pixel velocity per tick in 1/256ths
    int32_t    vy_q8;
    uint8_t    w;       // bbox width in pixels
    uint8_t    h;       // bbox height in pixels
    uint8_t    facing;  // 0 = left, 1 = right
    uint8_t    timer;   // generic countdown frames
    int16_t    spawn_tx;
    int16_t    spawn_ty;
};

static constexpr int MAX_ENTITIES = 48;
static Entity entities[MAX_ENTITIES];
static int    entity_count = 0;

static Entity* alloc_entity() {
    for (int i = 0; i < MAX_ENTITIES; i++) {
        if (entities[i].kind == EK_DEAD) {
            entities[i] = Entity{};
            return &entities[i];
        }
    }
    if (entity_count < MAX_ENTITIES) {
        Entity* e = &entities[entity_count++];
        *e = Entity{};
        return e;
    }
    return nullptr;
}

static void spawn_entity(EntityKind k, int tx, int ty) {
    Entity* e = alloc_entity();
    if (!e) return;
    e->kind     = k;
    e->x_q8     = (int32_t)tx * TILE * 256;
    e->y_q8     = (int32_t)ty * TILE * 256;
    e->vx_q8   = 0;
    e->vy_q8   = 0;
    e->facing  = 0;
    e->spawn_tx = tx;
    e->spawn_ty = ty;
    switch (k) {
        case EK_COIN:        e->w = TILE - 4; e->h = TILE - 4; break;
        case EK_MUSHROOM:    e->w = TILE - 2; e->h = TILE - 2; e->vx_q8 = 60; break;
        case EK_STAR:        e->w = TILE - 2; e->h = TILE - 2; e->vx_q8 = 80; e->vy_q8 = -200; break;
        case EK_GOOMBA:      e->w = TILE - 2; e->h = TILE - 2; e->vx_q8 = -40; break;
        case EK_KOOPA:       e->w = TILE - 2; e->h = TILE - 2; e->vx_q8 = -36; break;
        case EK_KOOPA_SHELL: e->w = TILE - 2; e->h = TILE - 2; break;
        case EK_KOOPA_SLIDE: e->w = TILE - 2; e->h = TILE - 2; break;
        case EK_COIN_POP:    e->w = 0;        e->h = 0;        e->timer = 40; break;
        case EK_BUMP_PARTICLE: e->w = 4;      e->h = 4;        e->timer = 18; break;
        default: break;
    }
}

