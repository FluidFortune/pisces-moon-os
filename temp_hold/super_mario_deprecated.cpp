// ─────────────────────────────────────────────
//  PER-DEVICE GEOMETRY
//
//  TILE = pixel size of one logical tile on this device.
//  VIEW_W / VIEW_H = the rectangle of pixels the game draws
//  into. For touch kiosks the bottom strip belongs to the
//  virtual D-pad chrome and must not be touched here.
//  HUD_H = height of the top status bar (lives/coins/world/time).
//
//  Levels are LEVEL_ROWS tiles tall regardless of device. The
//  device's TILE size determines how many tiles fit vertically;
//  on Cardputer and Pager the world is rendered with the top
//  tiles trimmed to fit, so level designs keep important
//  geometry in the bottom half.
// ─────────────────────────────────────────────

#ifdef DEVICE_CARDPUTER_ADV
static constexpr int VIEW_W   = 240;
static constexpr int VIEW_H   = 135;
static constexpr int TILE     = 10;
static constexpr int HUD_H    = 9;
#elif defined(DEVICE_TLORAPAGER)
static constexpr int VIEW_W   = 480;
static constexpr int VIEW_H   = 222;
static constexpr int TILE     = 14;
static constexpr int HUD_H    = 14;
#elif defined(DEVICE_C28P)
// C28P portrait: game lives in the top 200px above the virtual
// D-pad. 240/15 = 16 tiles wide, (200-12)/14 = ~13 tiles tall.
static constexpr int VIEW_W   = 240;
static constexpr int VIEW_H   = 200;
static constexpr int TILE     = 14;
static constexpr int HUD_H    = 12;
#elif defined(DEVICE_MAXINE)
// Maxine portrait: top 520px game area above the D-pad.
// 480/15 = 32 tiles wide visible. 14 tiles tall fits the level.
static constexpr int VIEW_W   = 480;
static constexpr int VIEW_H   = 520;
static constexpr int TILE     = 30;
static constexpr int HUD_H    = 22;
#else
// T-Deck Plus 320x240
static constexpr int VIEW_W   = 320;
static constexpr int VIEW_H   = 240;
static constexpr int TILE     = 16;
static constexpr int HUD_H    = 14;
#endif

static constexpr int LEVEL_ROWS = 13;
static constexpr int PLAY_H     = VIEW_H - HUD_H;
static constexpr int VIS_ROWS   = (PLAY_H / TILE);   // tiles visible vertically
static constexpr int VIS_COLS   = (VIEW_W / TILE);   // tiles visible horizontally

// ─────────────────────────────────────────────
//  VIEW PLACEMENT
//
//  T-Deck and Pager render the game centered in their display.
//  Touch kiosks (C28P, Maxine) MUST anchor at y=0 so the bottom
//  rows of the display stay reserved for the D-pad chrome.
// ─────────────────────────────────────────────
static int vx() {
    int w = gfx->width();
    return (w > VIEW_W) ? (w - VIEW_W) / 2 : 0;
}
static int vy() {
#if defined(DEVICE_C28P) || defined(DEVICE_MAXINE)
    return 0;
#else
    int h = gfx->height();
    return (h > VIEW_H) ? (h - VIEW_H) / 2 : 0;
#endif
}

// ─────────────────────────────────────────────
//  TILE TYPES + LOOKUP
//
//  TF_ flags describe behavior. SOLID blocks collide on all
//  sides. PLATFORM lets the player jump up through from below
//  but stand on top. KILL kills the player instantly. COIN
//  is a pickup. BUMP is a question/brick block that pops when
//  hit from underneath. GOAL is the level-end flagpole. PIPE
//  is solid + visually distinct.
// ─────────────────────────────────────────────
enum TileFlag {
    TF_EMPTY    = 0,
    TF_SOLID    = 1 << 0,
    TF_PLATFORM = 1 << 1,
    TF_KILL     = 1 << 2,
    TF_COIN     = 1 << 3,
    TF_BUMP     = 1 << 4,
    TF_GOAL     = 1 << 5,
    TF_PIPE     = 1 << 6,
};

struct TileDef {
    char     ch;
    uint8_t  flags;
    uint16_t color;
    uint16_t accent;
};

static const TileDef TILE_LOOKUP[] = {
    { '.', TF_EMPTY,                0x0000, 0x0000 },  // sky
    { ' ', TF_EMPTY,                0x0000, 0x0000 },  // sky
    { '#', TF_SOLID,                0x9261, 0x6105 },  // ground/dirt
    { 'B', TF_SOLID,                0xA284, 0x6105 },  // brick (solid bedrock)
    { 'b', TF_SOLID | TF_BUMP,      0xC388, 0x8208 },  // brick (poppable)
    { '?', TF_SOLID | TF_BUMP,      0xFD20, 0xC300 },  // question block
    { '=', TF_PLATFORM,             0xC388, 0x8208 },  // one-way platform
    { '|', TF_SOLID | TF_PIPE,      0x0660, 0x0420 },  // pipe body
    { '_', TF_SOLID | TF_PIPE,      0x07E0, 0x0420 },  // pipe top
    { '^', TF_KILL,                 0xC618, 0x8410 },  // spike
    { '~', TF_KILL,                 0xF800, 0xC000 },  // lava
    { 'F', TF_GOAL,                 0x07E0, 0xFFFF },  // flagpole
    { 'X', TF_SOLID,                0x39E7, 0x18C3 },  // dark stone
    { 'C', TF_SOLID,                0x39E7, 0x18C3 },  // castle stone
    { 0,   0,                       0,      0      },
};

static const TileDef* lookup_tile(char c) {
    for (int i = 0; TILE_LOOKUP[i].ch != 0; i++) {
        if (TILE_LOOKUP[i].ch == c) return &TILE_LOOKUP[i];
    }
    return &TILE_LOOKUP[0];  // default: empty/sky
}

// Convenience predicate: is this character a "render-as-tile"?
// (Anything in TILE_LOOKUP. Entities and pickups go through
// separate sprite lists rather than rendering tiles directly.)
static bool is_passable_for_lookup(char c) {
    const TileDef* t = lookup_tile(c);
    return (t->flags & (TF_SOLID | TF_PLATFORM)) == 0;
}

