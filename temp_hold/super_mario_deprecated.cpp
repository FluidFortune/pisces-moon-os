//  mario_bros.cpp — Pisces Moon original platformer
//
//  This is NOT a port of Nintendo's Super Mario Bros. The
//  source code is entirely original, the level designs are
//  hand-crafted for Pisces Moon, the protagonist is "Captain
//  Pisces" (the jumping astronaut), and the visual style is
//  our own. The genre is the genre — 2D scrolling platformer
//  with running, jumping, stomping enemies, and coin pickups.
//
//  ENGINE
//
//  Tile world: 16-pixel logical tiles, levels up to 192 tiles
//  wide x 13 tiles tall. Player position kept as fixed-point
//  tile coordinates (1/256ths of a tile) so physics is stable
//  on every device regardless of frame rate.
//
//  Physics: fixed gravity, variable-height jump (hold = higher
//  apex), terminal fall velocity, horizontal acceleration with
//  friction. Tile-snapped AABB collision: at each step, X and Y
//  are resolved separately so corners don't catch.
//
//  Camera: scrolls right when player crosses the 40% threshold
//  of the viewport. Never scrolls back (classic SMB rule).
//
//  Enemies: walker (Goomba-style) and shell-turtle (Koopa-style).
//  Both walk left until they hit a wall, then reverse. Stomping
//  kills walker; stomping turtle puts it into shell state, which
//  the player can then kick. Touching either kills the player
//  if they're not stomping from above (descending vy > 0).
//
//  Hazards: pits (gaps in the floor with no tiles below the
//  death line) and spikes. Both kill instantly.
//
//  Power-ups: coin (score +200), mushroom (one extra hit before
//  death), star (10s of invincibility — flashes player sprite,
//  enemies die on touch).
//
//  Goal: a flagpole (`F` tile) at the end of every level. Touch
//  it to win and advance to the next level. Furthest level
//  reached is persisted to NoSQL so progress survives reboots.
//
//  DEVICES
//
//  All five: T-Deck Plus, T-LoRa Pager, Cardputer ADV, C28P,
//  Maxine. Per-device TILE/viewport scaling. Touch kiosks reuse
//  the existing virtual D-pad chrome (c28p_dpad / maxine_dpad).
//  Keyboard devices use pm_read_nes_input() — A = jump, left/
//  right = move, B = run (faster horizontal speed).
//
//  LEVEL DATA
