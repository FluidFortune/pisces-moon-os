// ─────────────────────────────────────────────
//  MAIN GAME LOOP
// ─────────────────────────────────────────────
void run_mario_bros() {
    pm_game_audio_begin();
#ifdef DEVICE_C28P
    c28p_dpad_render();
#endif
#ifdef DEVICE_MAXINE
    maxine_dpad_render();
#endif

    mario_load_progress();
    current_level = furthest_reached;
    coins = 0;
    score = 0;
    lives = 3;

    title_screen();
    if (current_level < 0) return;   // user quit from title

    load_level(current_level);

    uint32_t last_frame = millis();

    while (true) {
        PMNesInput in = pm_read_nes_input(true);
        if (in.quit) {
            mario_save_progress();
            return;
        }

        update_player(in);
        for (int i = 0; i < MAX_ENTITIES; i++) update_entity(entities[i]);

        // Tick the in-game timer down once per second.
        if (millis() - time_last_tick >= 1000) {
            time_last_tick += 1000;
            if (time_left > 0) time_left--;
            if (time_left == 0 && !player_dead && !level_won) {
                hurt_player();
            }
        }

        // Draw
        clear_play_area();
        draw_world();
        draw_entities();
        draw_player();
        draw_hud();

        // State transitions
        if (level_won) {
            level_complete_screen();
            if (current_level >= furthest_reached) {
                furthest_reached = current_level + 1;
                if (furthest_reached > NUM_LEVELS - 1)
                    furthest_reached = NUM_LEVELS - 1;
                mario_save_progress();
            }
            current_level++;
            if (current_level >= NUM_LEVELS) {
                game_complete_screen();
                return;
            }
            load_level(current_level);
            last_frame = millis();
            continue;
        }

        if (player_dead && millis() - death_anim_start > 1200) {
            lives--;
            if (!death_screen()) {
                game_complete_screen();   // shows final score
                return;
            }
            load_level(current_level);
            last_frame = millis();
            continue;
        }

        // Frame pacing — aim for ~60Hz
        uint32_t now = millis();
        uint32_t elapsed = now - last_frame;
        if (elapsed < 16) delay(16 - elapsed);
        last_frame = millis();
        yield();
    }
}

