// ─────────────────────────────────────────────
//  NOSQL PERSISTENCE
//
//  We keep one tiny entry in the "settings" NoSQL category:
//    title="mario_progress" content="<level_index>"
//  Loaded once on game start, written when a level is cleared.
// ─────────────────────────────────────────────
static void mario_load_progress() {
    furthest_reached = 0;
    nosql_init("settings");
    int total = nosql_get_count("settings");
    String t, c;
    for (int i = 0; i < total; i++) {
        if (!nosql_get_entry("settings", i, t, c)) continue;
        if (t == "mario_progress") {
            int v = c.toInt();
            if (v < 0) v = 0;
            if (v > NUM_LEVELS - 1) v = NUM_LEVELS - 1;
            furthest_reached = v;
            return;
        }
    }
}

static void mario_save_progress() {
    nosql_init("settings");
    char buf[8];
    snprintf(buf, sizeof(buf), "%d", furthest_reached);
    nosql_save_entry("settings", "mario_progress", buf);
}

// ─────────────────────────────────────────────
//  LEVEL LOAD
//
//  Copies the const level rows into the mutable grid, walks
//  every cell extracting entities, and finds the player spawn.
// ─────────────────────────────────────────────
static void load_level(int idx) {
    const LevelDef& ld = LEVELS[idx];
    int w = (int)strlen(ld.rows[0]);
    if (w > MAX_LEVEL_W) w = MAX_LEVEL_W;
    level_w = w;

    // Clear entities first
    for (int i = 0; i < MAX_ENTITIES; i++) entities[i].kind = EK_DEAD;
    entity_count = 0;

    int player_spawn_tx = 2;
    int player_spawn_ty = LEVEL_ROWS - 3;

    // Copy + extract
    for (int y = 0; y < LEVEL_ROWS; y++) {
        const char* src = ld.rows[y];
        int srcLen = (int)strlen(src);
        for (int x = 0; x < w; x++) {
            char c = (x < srcLen) ? src[x] : '.';
            switch (c) {
                case 'P':
                    player_spawn_tx = x;
                    player_spawn_ty = y;
                    grid[y][x] = '.';
                    break;
                case '*':
                    spawn_entity(EK_COIN, x, y);
                    grid[y][x] = '.';
                    break;
                case 'M':
                    spawn_entity(EK_MUSHROOM, x, y);
                    grid[y][x] = '.';
                    break;
                case 'S':
                    spawn_entity(EK_STAR, x, y);
                    grid[y][x] = '.';
                    break;
                case 'g':
                    spawn_entity(EK_GOOMBA, x, y);
                    grid[y][x] = '.';
                    break;
                case 'k':
                    spawn_entity(EK_KOOPA, x, y);
                    grid[y][x] = '.';
                    break;
                default:
                    grid[y][x] = c;
                    break;
            }
        }
        grid[y][w] = '\0';
    }

    // Initialize player
    player.x_q8 = (int32_t)player_spawn_tx * TILE * 256;
    player.y_q8 = (int32_t)player_spawn_ty * TILE * 256;
    player.vx_q8 = 0;
    player.vy_q8 = 0;
    player.w = TILE - 4;
    player.h = TILE - 2;
    player.on_ground = 0;
    player.facing = 1;
    // Preserve big/star state across levels-in-life? Classic SMB
    // gives you small at the start of each level if you died, big
    // if you cleared. Simpler: always start small, grow on power-up.
    player.big = 0;
    player.star_timer = 0;
    player.hurt_timer = 0;
    player.jump_hold = 0;

    cam_x_q8 = 0;
    time_left = 400;
    time_last_tick = millis();
    current_level = idx;
    level_won = false;
    player_dead = false;
}

// ─────────────────────────────────────────────
//  RENDER HELPERS
//
//  All rendering is in display coordinates (vx() + ..., vy() +
//  HUD_H + ...). Tile sprites are drawn as flat rectangles with
//  accent lines/dots to suggest pixel art without needing a
//  bitmap. Entities are drawn as small filled shapes.
// ─────────────────────────────────────────────
static int px_x(int32_t world_x_q8) {
    return vx() + (int)((world_x_q8 - cam_x_q8) >> 8);
}
static int px_y(int32_t world_y_q8) {
    return vy() + HUD_H + (int)(world_y_q8 >> 8);
}

static void draw_tile_cell(int tx, int ty) {
    char c = tile_at(tx, ty);
    const TileDef* t = lookup_tile(c);
    if (t->flags == TF_EMPTY) return;

    int px = vx() + tx * TILE - (int)(cam_x_q8 >> 8);
    int py = vy() + HUD_H + ty * TILE;
    if (px + TILE <= vx() || px >= vx() + VIEW_W) return;   // offscreen

    // Block fill
    if (c == '^') {
        // Spikes: triangle row sitting on top of the underlying tile cell
        gfx->fillRect(px, py + TILE / 2, TILE, TILE / 2, 0x4208);
        int tip_y = py + 2;
        int base_y = py + TILE / 2 + 1;
        for (int i = 0; i < TILE; i += 3) {
            gfx->fillTriangle(px + i, base_y,
                              px + i + 1, tip_y,
                              px + i + 3, base_y,
                              0xC618);
        }
        return;
    }
    if (c == '~') {
        gfx->fillRect(px, py, TILE, TILE, 0xF800);
        // Lava shimmer line
        int shimmer = (int)((millis() / 80) % TILE);
        gfx->drawFastHLine(px, py + (shimmer + 0) % TILE, TILE, 0xFD20);
        gfx->drawFastHLine(px, py + (shimmer + TILE/2) % TILE, TILE, 0xFFE0);
        return;
    }
    if (c == 'F') {
        // Flagpole: vertical line + a flag triangle. Top of pole at row top.
        gfx->fillRect(px + TILE/2 - 1, py - TILE * 6, 2, TILE * 7, 0xC618);
        gfx->fillTriangle(px + TILE/2, py - TILE * 6,
                          px + TILE - 1, py - TILE * 5,
                          px + TILE/2, py - TILE * 5 + 2,
                          t->color);
        // Pole base
        gfx->fillRect(px + 2, py + TILE - 3, TILE - 4, 3, 0x8410);
        return;
    }
    if (c == '?') {
        gfx->fillRect(px, py, TILE, TILE, t->color);
        gfx->drawRect(px, py, TILE, TILE, t->accent);
        // Question mark glyph (centered)
        int cx = px + TILE / 2;
        int cy = py + TILE / 2;
        gfx->setTextSize(1);
        gfx->setTextColor(0x0000);
        gfx->setCursor(cx - 3, cy - 4);
        gfx->print("?");
        return;
    }
    if (c == '_') {
        // Pipe top: green slab with darker accent
        gfx->fillRect(px - 1, py, TILE + 2, TILE, t->color);
        gfx->drawRect(px - 1, py, TILE + 2, TILE, t->accent);
        gfx->fillRect(px + 1, py + 2, TILE - 2, TILE - 4, 0x0420);
        return;
    }
    if (c == '|') {
        gfx->fillRect(px, py, TILE, TILE, t->color);
        gfx->drawFastVLine(px, py, TILE, t->accent);
        gfx->drawFastVLine(px + TILE - 1, py, TILE, t->accent);
        return;
    }
    if (c == 'b' || c == 'B') {
        gfx->fillRect(px, py, TILE, TILE, t->color);
        // Brick lines
        gfx->drawRect(px, py, TILE, TILE, t->accent);
        gfx->drawFastHLine(px, py + TILE / 2, TILE, t->accent);
        gfx->drawFastVLine(px + TILE / 2, py, TILE / 2, t->accent);
        gfx->drawFastVLine(px + TILE / 4, py + TILE / 2, TILE / 2, t->accent);
        return;
    }
    if (c == '=') {
        // Platform: thin top stripe + ribbed underside
        gfx->fillRect(px, py, TILE, TILE / 2, t->color);
        gfx->fillRect(px, py + TILE / 2, TILE, TILE / 2, t->accent);
        gfx->drawRect(px, py, TILE, TILE, 0x4208);
        return;
    }
    if (c == 'X' || c == 'C') {
        gfx->fillRect(px, py, TILE, TILE, t->color);
        gfx->drawRect(px, py, TILE, TILE, t->accent);
        // Speckle
        gfx->drawPixel(px + 3, py + 2, t->accent);
        gfx->drawPixel(px + TILE - 4, py + TILE - 4, t->accent);
        return;
    }
    // Default ground/dirt
    gfx->fillRect(px, py, TILE, TILE, t->color);
    gfx->drawRect(px, py, TILE, TILE, t->accent);
    // Grass cap on the very top row of the ground band
    if (ty > 0 && lookup_tile(tile_at(tx, ty - 1))->flags == TF_EMPTY) {
        gfx->drawFastHLine(px, py, TILE, 0x07E0);
        gfx->drawFastHLine(px, py + 1, TILE, 0x0420);
    }
}

static void draw_world() {
    int cam_px = (int)(cam_x_q8 >> 8);
    int first_col = cam_px / TILE;
    if (first_col < 0) first_col = 0;
    int last_col = first_col + VIS_COLS + 1;
    if (last_col > level_w) last_col = level_w;

    for (int tx = first_col; tx < last_col; tx++) {
        for (int ty = 0; ty < LEVEL_ROWS; ty++) {
            draw_tile_cell(tx, ty);
        }
    }
}

static void draw_entity(const Entity& e) {
    int px = px_x(e.x_q8);
    int py = px_y(e.y_q8);
    if (px + e.w < vx() || px > vx() + VIEW_W) return;

    switch (e.kind) {
        case EK_COIN: {
            int cx = px + e.w / 2;
            int cy = py + e.h / 2;
            int r  = e.w / 2 - 1;
            if (r < 2) r = 2;
            gfx->fillCircle(cx, cy, r, 0xFFE0);
            gfx->drawCircle(cx, cy, r, 0xFD20);
            gfx->drawFastVLine(cx, cy - r + 2, r * 2 - 4, 0xFD20);
            break;
        }
        case EK_MUSHROOM: {
            // Red cap, white spots, peach base
            gfx->fillRect(px, py + e.h / 2, e.w, e.h / 2, 0xFDB8);
            gfx->fillRect(px, py, e.w, e.h / 2, 0xF800);
            gfx->fillRect(px + 2, py + 2, 3, 3, 0xFFFF);
            gfx->fillRect(px + e.w - 5, py + 2, 3, 3, 0xFFFF);
            break;
        }
        case EK_STAR: {
            uint16_t col = ((millis() / 80) & 1) ? 0xFFE0 : 0xFFFF;
            int cx = px + e.w / 2;
            int cy = py + e.h / 2;
            int r = e.w / 2;
            gfx->fillTriangle(cx, cy - r, cx - r, cy + r, cx + r, cy + r, col);
            gfx->fillTriangle(cx, cy + r, cx - r, cy - r/2, cx + r, cy - r/2, col);
            break;
        }
        case EK_GOOMBA: {
            // Brown mushroom-shaped walker
            gfx->fillRect(px, py + e.h / 2, e.w, e.h / 2, 0x8208);
            gfx->fillRect(px, py, e.w, e.h / 2 + 1, 0x6105);
            // Eyes
            gfx->fillRect(px + 2, py + 3, 2, 2, 0xFFFF);
            gfx->fillRect(px + e.w - 4, py + 3, 2, 2, 0xFFFF);
            gfx->fillRect(px + 3, py + 4, 1, 1, 0x0000);
            gfx->fillRect(px + e.w - 3, py + 4, 1, 1, 0x0000);
            break;
        }
        case EK_KOOPA: {
            // Green turtle: shell + head
            gfx->fillRect(px, py + 2, e.w, e.h - 2, 0x07E0);
            gfx->drawRect(px, py + 2, e.w, e.h - 2, 0x0420);
            // Head poking out depending on facing
            int hx = e.facing ? (px + e.w - 3) : px;
            gfx->fillRect(hx, py, 3, 4, 0xFFE0);
            break;
        }
        case EK_KOOPA_SHELL:
        case EK_KOOPA_SLIDE: {
            gfx->fillRect(px, py + 2, e.w, e.h - 2, 0x07E0);
            gfx->drawRect(px, py + 2, e.w, e.h - 2, 0xFFE0);
            // Inner darker stripe
            gfx->drawFastHLine(px + 1, py + e.h / 2, e.w - 2, 0x0420);
            break;
        }
        case EK_COIN_POP: {
            gfx->setTextSize(1);
            gfx->setTextColor(0xFFE0);
            gfx->setCursor(px, py - (40 - e.timer) / 2);
            gfx->print("+200");
            break;
        }
        case EK_BUMP_PARTICLE: {
            gfx->fillRect(px, py, e.w, e.h, 0xC388);
            break;
        }
        default: break;
    }
}

static void draw_entities() {
    for (int i = 0; i < MAX_ENTITIES; i++) {
        if (entities[i].kind != EK_DEAD) draw_entity(entities[i]);
    }
}

static void draw_player() {
    int px = px_x(player.x_q8);
    int py = px_y(player.y_q8);

    // Star flicker: skip every other frame while invincible
    if (player.star_timer > 0 && ((player.star_timer / 4) & 1)) return;
    if (player.hurt_timer > 0 && (player.hurt_timer & 1)) return;

    int h = player.h;
    int w = player.w;
    uint16_t suit = 0x07FF;   // Captain Pisces — cyan space suit
    uint16_t helm = 0xFFFF;
    uint16_t visor = 0x001F;
    if (player.big) {
        h = player.h;   // (kept same; big mode is a hit-buffer, not a size change here)
    }

    // Body
    gfx->fillRect(px, py + h / 2, w, h / 2, suit);
    // Head
    gfx->fillRect(px + 1, py, w - 2, h / 2, helm);
    // Visor
    int vy0 = py + 2;
    if (player.facing) {
        gfx->fillRect(px + w / 2 - 1, vy0, w / 2, 3, visor);
    } else {
        gfx->fillRect(px + 1,       vy0, w / 2, 3, visor);
    }
    // Backpack tank highlight
    gfx->drawFastVLine(player.facing ? px : px + w - 1, py + h / 2, h / 2 - 1, 0xC618);
}

