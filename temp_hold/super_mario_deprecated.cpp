// ─────────────────────────────────────────────
//  COLLISION HELPERS
//
//  Convert a pixel AABB to the range of tile cells it overlaps,
//  then check each cell's tile flags.
// ─────────────────────────────────────────────
struct AABB { int32_t x, y, w, h; };   // pixel-q8 coords; w,h in pixels

static bool aabb_overlap(int32_t ax, int32_t ay, int aw, int ah,
                         int32_t bx, int32_t by, int bw, int bh) {
    return (ax >> 8) < ((bx >> 8) + bw) &&
           ((ax >> 8) + aw) > (bx >> 8) &&
           (ay >> 8) < ((by >> 8) + bh) &&
           ((ay >> 8) + ah) > (by >> 8);
}

static bool tile_is_solid(char c, bool from_above) {
    const TileDef* t = lookup_tile(c);
    if (t->flags & TF_SOLID) return true;
    if ((t->flags & TF_PLATFORM) && from_above) return true;
    return false;
}

// Resolve horizontal movement: try to move by dx (pixel-q8). If we'd
// collide with a solid tile, snap to its edge. Returns true if the
// move was blocked.
static bool move_horiz(int32_t& x_q8, int32_t y_q8, int w, int h, int32_t dx) {
    int32_t new_x = x_q8 + dx;
    int px = (int)(new_x >> 8);
    int py = (int)(y_q8 >> 8);
    int tx_lo, tx_hi;
    if (dx > 0) {
        tx_lo = tx_hi = (px + w - 1) / TILE;
    } else if (dx < 0) {
        tx_lo = tx_hi = px / TILE;
    } else {
        x_q8 = new_x;
        return false;
    }
    int ty_lo = py / TILE;
    int ty_hi = (py + h - 1) / TILE;
    for (int ty = ty_lo; ty <= ty_hi; ty++) {
        for (int tx = tx_lo; tx <= tx_hi; tx++) {
            char c = tile_at(tx, ty);
            if (tile_is_solid(c, /*from_above=*/false)) {
                if (dx > 0) new_x = (int32_t)(tx * TILE - w) * 256;
                else        new_x = (int32_t)((tx + 1) * TILE) * 256;
                x_q8 = new_x;
                return true;
            }
        }
    }
    x_q8 = new_x;
    return false;
}

// Resolve vertical movement. Returns +1 if landed on ground, -1 if
// bumped head into ceiling, 0 if free.
//
// Also reports the tile that was hit (out_hit_tx, out_hit_ty, out_hit_c)
// when the player hits head-up — used to pop ? blocks and bricks.
static int move_vert(int32_t x_q8, int32_t& y_q8, int w, int h, int32_t dy,
                     int* out_hit_tx = nullptr, int* out_hit_ty = nullptr,
                     char* out_hit_c = nullptr) {
    int32_t new_y = y_q8 + dy;
    int px = (int)(x_q8 >> 8);
    int py = (int)(new_y >> 8);
    int ty_lo, ty_hi;
    bool from_above = (dy > 0);
    if (dy > 0) {
        ty_lo = ty_hi = (py + h - 1) / TILE;
    } else if (dy < 0) {
        ty_lo = ty_hi = py / TILE;
    } else {
        y_q8 = new_y;
        return 0;
    }
    int tx_lo = px / TILE;
    int tx_hi = (px + w - 1) / TILE;
    for (int ty = ty_lo; ty <= ty_hi; ty++) {
        for (int tx = tx_lo; tx <= tx_hi; tx++) {
            char c = tile_at(tx, ty);
            if (tile_is_solid(c, from_above)) {
                if (dy > 0) {
                    new_y = (int32_t)(ty * TILE - h) * 256;
                    y_q8 = new_y;
                    return +1;
                } else {
                    new_y = (int32_t)((ty + 1) * TILE) * 256;
                    y_q8 = new_y;
                    if (out_hit_tx) *out_hit_tx = tx;
                    if (out_hit_ty) *out_hit_ty = ty;
                    if (out_hit_c)  *out_hit_c  = c;
                    return -1;
                }
            }
        }
    }
    y_q8 = new_y;
    return 0;
}

// Quick check: is the cell ty just below the player's bbox solid? Used
// to test "still standing on ground" so the player doesn't levitate
// when walking off an edge.
static bool standing_on_ground(int32_t x_q8, int32_t y_q8, int w, int h) {
    int px = (int)(x_q8 >> 8);
    int py = (int)(y_q8 >> 8);
    int ty = (py + h) / TILE;
    int tx_lo = px / TILE;
    int tx_hi = (px + w - 1) / TILE;
    // Only count as ground if the foot is within 1 pixel of the tile top.
    if (((py + h) % TILE) != 0) return false;
    for (int tx = tx_lo; tx <= tx_hi; tx++) {
        char c = tile_at(tx, ty);
        if (tile_is_solid(c, /*from_above=*/true)) return true;
    }
    return false;
}

// ─────────────────────────────────────────────
//  PHYSICS CONSTANTS  (all in q8 pixel units per tick)
//
//  Game runs at ~60Hz; one "tick" = one frame.
// ─────────────────────────────────────────────
static constexpr int32_t GRAVITY      = 70;
static constexpr int32_t MAX_FALL     = 700;
static constexpr int32_t WALK_ACCEL   = 25;
static constexpr int32_t RUN_ACCEL    = 40;
static constexpr int32_t WALK_MAX     = 320;
static constexpr int32_t RUN_MAX      = 520;
static constexpr int32_t FRICTION     = 22;
static constexpr int32_t JUMP_IMPULSE = -780;
static constexpr int32_t JUMP_HOLD    = -55;
static constexpr int      JUMP_HOLD_FRAMES = 14;

// ─────────────────────────────────────────────
//  POWER-UP EFFECTS / DEATH
// ─────────────────────────────────────────────
static void give_coin() {
    coins++;
    score += 200;
    pm_game_audio_fx_line();
}

static void grow_player() {
    if (!player.big) {
        player.big = 1;
        score += 1000;
    } else {
        score += 1000;   // already big: bonus
    }
    pm_game_audio_fx_drop();
}

static void give_star() {
    player.star_timer = 600;   // 10 seconds at 60Hz
    score += 1000;
    pm_game_audio_fx_drop();
}

static void hurt_player() {
    if (player.hurt_timer > 0) return;
    if (player.star_timer > 0) return;
    if (player.big) {
        player.big = 0;
        player.hurt_timer = 90;
        return;
    }
    player_dead = true;
    death_anim_start = millis();
    player.vy_q8 = -800;
    pm_game_audio_fx_drop();
}

// ─────────────────────────────────────────────
//  ENEMY UPDATE
// ─────────────────────────────────────────────
static void update_entity(Entity& e) {
    if (e.kind == EK_DEAD) return;

    // Common gravity for things that fall
    bool falls = (e.kind == EK_GOOMBA || e.kind == EK_KOOPA ||
                  e.kind == EK_KOOPA_SHELL || e.kind == EK_KOOPA_SLIDE ||
                  e.kind == EK_MUSHROOM || e.kind == EK_STAR);
    if (falls) {
        e.vy_q8 += GRAVITY;
        if (e.vy_q8 > MAX_FALL) e.vy_q8 = MAX_FALL;
    }

    // Movement with tile collision (only for moving solids)
    if (e.kind == EK_GOOMBA || e.kind == EK_KOOPA ||
        e.kind == EK_KOOPA_SLIDE || e.kind == EK_MUSHROOM ||
        e.kind == EK_STAR) {
        int32_t x = e.x_q8;
        int32_t y = e.y_q8;
        bool blocked = move_horiz(x, y, e.w, e.h, e.vx_q8);
        if (blocked) {
            e.vx_q8 = -e.vx_q8;
            e.facing = !e.facing;
        }
        int vr = move_vert(x, y, e.w, e.h, e.vy_q8);
        if (vr > 0) e.vy_q8 = 0;
        if (vr < 0) e.vy_q8 = 0;
        e.x_q8 = x;
        e.y_q8 = y;

        // Edge-detect for walkers (so they don't walk off cliffs).
        // Star is allowed to fall off.
        if ((e.kind == EK_GOOMBA || e.kind == EK_KOOPA) && vr > 0) {
            int foot_tx = e.facing
                ? (int)((e.x_q8 >> 8) + e.w) / TILE
                : (int)(e.x_q8 >> 8) / TILE - 1;
            int foot_ty = (int)((e.y_q8 >> 8) + e.h) / TILE;
            char c = tile_at(foot_tx, foot_ty);
            if (!tile_is_solid(c, /*from_above=*/true)) {
                e.vx_q8 = -e.vx_q8;
                e.facing = !e.facing;
            }
        }

        // Fell into the void (below level)
        int py = (int)(e.y_q8 >> 8);
        if (py > LEVEL_ROWS * TILE + 60) {
            e.kind = EK_DEAD;
            return;
        }
    }

    if (e.kind == EK_KOOPA_SHELL) {
        // Static shell on ground until kicked. Apply gravity so it
        // falls if a brick under it is destroyed.
        int32_t x = e.x_q8;
        int32_t y = e.y_q8;
        int vr = move_vert(x, y, e.w, e.h, e.vy_q8);
        if (vr != 0) e.vy_q8 = 0;
        e.y_q8 = y;
        // Auto-revive after a few seconds of idle? Classic SMB does.
        e.timer++;
        if (e.timer > 240) {
            e.kind = EK_KOOPA;
            e.vx_q8 = -36;
            e.timer = 0;
        }
    }

    if (e.kind == EK_BUMP_PARTICLE) {
        e.vy_q8 += GRAVITY / 2;
        e.x_q8  += e.vx_q8;
        e.y_q8  += e.vy_q8;
        if (e.timer-- == 0) e.kind = EK_DEAD;
    }
    if (e.kind == EK_COIN_POP) {
        if (e.timer-- == 0) e.kind = EK_DEAD;
    }
}

// ─────────────────────────────────────────────
//  PLAYER vs ENTITY INTERACTIONS
// ─────────────────────────────────────────────
static void resolve_player_entities() {
    int32_t px = player.x_q8;
    int32_t py = player.y_q8;
    int     pw = player.w;
    int     ph = player.h;

    for (int i = 0; i < MAX_ENTITIES; i++) {
        Entity& e = entities[i];
        if (e.kind == EK_DEAD) continue;
        if (!aabb_overlap(px, py, pw, ph, e.x_q8, e.y_q8, e.w, e.h)) continue;

        switch (e.kind) {
            case EK_COIN:
                give_coin();
                {
                    Entity* p = alloc_entity();
                    if (p) {
                        p->kind = EK_COIN_POP;
                        p->x_q8 = e.x_q8;
                        p->y_q8 = e.y_q8;
                        p->timer = 40;
                    }
                }
                e.kind = EK_DEAD;
                break;

            case EK_MUSHROOM:
                grow_player();
                e.kind = EK_DEAD;
                break;

            case EK_STAR:
                give_star();
                e.kind = EK_DEAD;
                break;

            case EK_GOOMBA: {
                // Stomp if descending and player's feet are at/above
                // the goomba's middle.
                int p_foot = (int)((player.y_q8 + player.h * 256) >> 8);
                int g_mid  = (int)((e.y_q8 >> 8) + e.h / 2);
                if (player.vy_q8 > 0 && p_foot <= g_mid + 2) {
                    e.kind = EK_DEAD;
                    score += 100;
                    player.vy_q8 = JUMP_IMPULSE / 2;
                    pm_game_audio_fx_line();
                } else if (player.star_timer > 0) {
                    e.kind = EK_DEAD;
                    score += 200;
                } else {
                    hurt_player();
                }
                break;
            }

            case EK_KOOPA: {
                int p_foot = (int)((player.y_q8 + player.h * 256) >> 8);
                int k_mid  = (int)((e.y_q8 >> 8) + e.h / 2);
                if (player.vy_q8 > 0 && p_foot <= k_mid + 2) {
                    e.kind   = EK_KOOPA_SHELL;
                    e.vx_q8  = 0;
                    e.timer  = 0;
                    score   += 100;
                    player.vy_q8 = JUMP_IMPULSE / 2;
                    pm_game_audio_fx_line();
                } else if (player.star_timer > 0) {
                    e.kind = EK_DEAD;
                    score += 200;
                } else {
                    hurt_player();
                }
                break;
            }

            case EK_KOOPA_SHELL: {
                // Kick: shell becomes a slider going away from player.
                int p_center = (int)((player.x_q8 >> 8) + player.w / 2);
                int e_center = (int)((e.x_q8 >> 8) + e.w / 2);
                if (p_center < e_center) {
                    e.vx_q8 = 480;
                    e.facing = 1;
                } else {
                    e.vx_q8 = -480;
                    e.facing = 0;
                }
                e.kind = EK_KOOPA_SLIDE;
                score += 50;
                break;
            }

            case EK_KOOPA_SLIDE: {
                // Sliding shell kills the player on touch — unless
                // they're descending onto it, then it stops.
                int p_foot = (int)((player.y_q8 + player.h * 256) >> 8);
                int k_mid  = (int)((e.y_q8 >> 8) + e.h / 2);
                if (player.vy_q8 > 0 && p_foot <= k_mid + 2) {
                    e.kind  = EK_KOOPA_SHELL;
                    e.vx_q8 = 0;
                    e.timer = 0;
                    player.vy_q8 = JUMP_IMPULSE / 2;
                } else if (player.star_timer > 0) {
                    e.kind = EK_DEAD;
                    score += 200;
                } else {
                    hurt_player();
                }
                break;
            }

            default: break;
        }
    }
}

// ─────────────────────────────────────────────
//  PLAYER UPDATE
// ─────────────────────────────────────────────
static void update_player(const PMNesInput& in) {
    if (player.hurt_timer > 0) player.hurt_timer--;
    if (player.star_timer > 0) player.star_timer--;

    if (player_dead) {
        // Death animation: player flies up briefly, then falls
        player.vy_q8 += GRAVITY;
        if (player.vy_q8 > MAX_FALL) player.vy_q8 = MAX_FALL;
        player.y_q8 += player.vy_q8;
        return;
    }

    // Horizontal input + accel
    int32_t accel = (in.b ? RUN_ACCEL : WALK_ACCEL);
    int32_t maxv  = (in.b ? RUN_MAX   : WALK_MAX);
    if (in.left) {
        player.vx_q8 -= accel;
        if (player.vx_q8 < -maxv) player.vx_q8 = -maxv;
        player.facing = 0;
    } else if (in.right) {
        player.vx_q8 += accel;
        if (player.vx_q8 > maxv) player.vx_q8 = maxv;
        player.facing = 1;
    } else {
        // Friction
        if (player.vx_q8 > FRICTION)  player.vx_q8 -= FRICTION;
        else if (player.vx_q8 < -FRICTION) player.vx_q8 += FRICTION;
        else player.vx_q8 = 0;
    }

    // Jump
    if (in.a && player.on_ground) {
        player.vy_q8 = JUMP_IMPULSE;
        player.on_ground = 0;
        player.jump_hold = JUMP_HOLD_FRAMES;
        pm_game_audio_fx_drop();
    } else if (in.a && player.jump_hold > 0) {
        player.vy_q8 += JUMP_HOLD;
        player.jump_hold--;
    } else {
        player.jump_hold = 0;
    }

    // Gravity
    player.vy_q8 += GRAVITY;
    if (player.vy_q8 > MAX_FALL) player.vy_q8 = MAX_FALL;

    // Horizontal collision
    move_horiz(player.x_q8, player.y_q8, player.w, player.h, player.vx_q8);
    // Don't run off the left edge of the level
    if (player.x_q8 < cam_x_q8) player.x_q8 = cam_x_q8;

    // Vertical collision
    int hit_tx, hit_ty;
    char hit_c;
    int vr = move_vert(player.x_q8, player.y_q8, player.w, player.h,
                       player.vy_q8, &hit_tx, &hit_ty, &hit_c);
    if (vr > 0) {
        player.vy_q8 = 0;
        player.on_ground = 1;
    } else if (vr < 0) {
        player.vy_q8 = 0;
        player.jump_hold = 0;
        // Bump tile from below
        if (hit_c == '?' || hit_c == 'b') {
            const TileDef* t = lookup_tile(hit_c);
            if (t->flags & TF_BUMP) {
                if (hit_c == '?') {
                    set_tile(hit_tx, hit_ty, 'B');   // becomes hard solid
                    // Spawn a coin one tile above
                    spawn_entity(EK_COIN_POP, hit_tx, hit_ty - 1);
                    coins++;
                    score += 200;
                } else if (hit_c == 'b') {
                    // If big, destroy. Else just rattle (spawn particle).
                    if (player.big) {
                        set_tile(hit_tx, hit_ty, '.');
                        // Spawn 4 brick particle entities
                        for (int p = 0; p < 4; p++) {
                            Entity* pe = alloc_entity();
                            if (!pe) break;
                            pe->kind = EK_BUMP_PARTICLE;
                            pe->x_q8 = (int32_t)(hit_tx * TILE + (p & 1 ? TILE - 4 : 2)) * 256;
                            pe->y_q8 = (int32_t)(hit_ty * TILE + (p < 2 ? 2 : TILE - 4)) * 256;
                            pe->vx_q8 = (p & 1) ? 200 : -200;
                            pe->vy_q8 = -400;
                            pe->w = 4; pe->h = 4;
                            pe->timer = 24;
                        }
                        score += 50;
                    }
                }
                pm_game_audio_fx_line();
            }
        }
    } else {
        player.on_ground = 0;
    }

    // Stick-on-ground sense: if we walked off an edge without
    // setting on_ground=0 via vert resolution, fix it.
    if (player.on_ground && !standing_on_ground(player.x_q8, player.y_q8,
                                                player.w, player.h)) {
        player.on_ground = 0;
    }

    // Hazard check: any KILL tile under the player's feet/body
    int pxx = (int)(player.x_q8 >> 8);
    int pyy = (int)(player.y_q8 >> 8);
    int tx_lo = pxx / TILE;
    int tx_hi = (pxx + player.w - 1) / TILE;
    int ty_lo = pyy / TILE;
    int ty_hi = (pyy + player.h - 1) / TILE;
    for (int ty = ty_lo; ty <= ty_hi; ty++) {
        for (int tx = tx_lo; tx <= tx_hi; tx++) {
            char c = tile_at(tx, ty);
            const TileDef* t = lookup_tile(c);
            if (t->flags & TF_KILL) {
                if (player.star_timer == 0 && player.hurt_timer == 0) {
                    hurt_player();
                }
            }
            if (t->flags & TF_GOAL) {
                level_won = true;
                score += 5000 + time_left * 50;
                return;
            }
        }
    }

    // Death plane (fell off bottom)
    if (pyy > LEVEL_ROWS * TILE + 40) {
        if (!player_dead) {
            player_dead = true;
            death_anim_start = millis();
            player.vy_q8 = -800;
        }
    }

    // Resolve player vs entities
    resolve_player_entities();

    // Camera: never moves backwards. Scroll right when player crosses
    // 40% of the viewport.
    int32_t target_cam = player.x_q8 - (int32_t)(VIEW_W * 256 * 4 / 10);
    if (target_cam > cam_x_q8) cam_x_q8 = target_cam;
    int32_t max_cam = (int32_t)((level_w * TILE - VIEW_W)) * 256;
    if (cam_x_q8 > max_cam) cam_x_q8 = max_cam;
    if (cam_x_q8 < 0) cam_x_q8 = 0;
}

