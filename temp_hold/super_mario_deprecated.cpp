static void draw_centered_text(const char* s, int y, uint16_t color, int size) {
    int char_w = 6 * size;
    int w = (int)strlen(s) * char_w;
    gfx->setTextSize(size);
    gfx->setTextColor(color);
    gfx->setCursor(vx() + (VIEW_W - w) / 2, vy() + y);
    gfx->print(s);
}

static void clear_play_area() {
    int ox = vx();
    int oy = vy();
    // Sky band
    gfx->fillRect(ox, oy + HUD_H, VIEW_W, PLAY_H, 0x549F);
    // Distant clouds (simple shapes)
    for (int i = 0; i < 4; i++) {
        int cx = ((int)((cam_x_q8 >> 8) / 6) + i * (VIEW_W / 3)) % (VIEW_W + 60) - 30;
        int cy = oy + HUD_H + 12 + (i & 1) * 6;
        gfx->fillCircle(ox + cx,      cy,     6, 0xFFFF);
        gfx->fillCircle(ox + cx + 7,  cy + 1, 7, 0xFFFF);
        gfx->fillCircle(ox + cx + 14, cy,     6, 0xFFFF);
    }
}

